//! Render a `README.md` for a generated component.
//!
//! The README's title matches the component name, and a "Generator Diagnostics" section
//! records the options the generator ran with and which generation heuristics fired (so a
//! reader can tell, for example, that the duplicate-credential pruning removed fields).

use crate::PackageName;

/// Generator inputs and heuristic outcomes recorded while generating a component, rendered into
/// the README's "Generator Diagnostics" table.
#[derive(Debug)]
pub(crate) struct Diagnostics {
    /// The tag filter passed to [`crate::generate`], if any. `None` means every tag was emitted.
    pub(crate) tag_filter: Option<Vec<String>>,
    /// Total operations emitted across all interfaces.
    pub(crate) operations: usize,
    /// Request fields dropped by the duplicate-credential pruning heuristic.
    pub(crate) pruned_credential_fields: usize,
}

/// Render the `README.md` for a generated component: a title matching the component name and a
/// `## Generator Diagnostics` section tabulating the options passed to the generator and whether
/// each heuristic triggered.
pub(crate) fn render(package: &PackageName, diagnostics: &Diagnostics) -> String {
    let name = &package.name;
    let package_id = match &package.version {
        Some(version) => format!("{}:{}@{version}", package.namespace, package.name),
        None => format!("{}:{}", package.namespace, package.name),
    };
    let tag_filter = match &diagnostics.tag_filter {
        Some(tags) if !tags.is_empty() => format!("`{}`", tags.join("`, `")),
        _ => "all tags".to_string(),
    };
    let prune = match diagnostics.pruned_credential_fields {
        0 => "enabled — not triggered".to_string(),
        1 => "enabled — **triggered**, 1 field pruned".to_string(),
        n => format!("enabled — **triggered**, {n} fields pruned"),
    };

    format!(
        "# {name}\n\
        \n\
        <!-- AUTOGENERATED by openapi-bindgen. Do not edit by hand. -->\n\
        \n\
        WebAssembly component bindings generated from an OpenAPI document.\n\
        \n\
        ## Generator Diagnostics\n\
        \n\
        The options this component was generated with, and whether each generation heuristic\n\
        triggered.\n\
        \n\
        | Setting | Value |\n\
        | --- | --- |\n\
        | Package | `{package_id}` |\n\
        | Tag filter | {tag_filter} |\n\
        | Operations generated | {operations} |\n\
        | Prune duplicate credential fields | {prune} |\n",
        operations = diagnostics.operations,
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn package() -> PackageName {
        PackageName::parse("autostamp:plaid@0.1.0").unwrap()
    }

    #[test]
    fn title_matches_component_name_and_lists_options() {
        let readme = render(
            &package(),
            &Diagnostics {
                tag_filter: None,
                operations: 199,
                pruned_credential_fields: 197,
            },
        );
        assert!(readme.starts_with("# plaid\n"));
        assert!(readme.contains("## Generator Diagnostics"));
        assert!(readme.contains("| Package | `autostamp:plaid@0.1.0` |"));
        assert!(readme.contains("| Tag filter | all tags |"));
        assert!(readme.contains("| Operations generated | 199 |"));
    }

    #[test]
    fn notes_when_prune_heuristic_triggers() {
        let readme = render(
            &package(),
            &Diagnostics {
                tag_filter: Some(vec!["billing".into()]),
                operations: 3,
                pruned_credential_fields: 2,
            },
        );
        assert!(readme.contains("| Tag filter | `billing` |"));
        assert!(readme.contains("**triggered**, 2 fields pruned"));
    }

    #[test]
    fn notes_when_prune_heuristic_does_not_trigger() {
        let readme = render(
            &package(),
            &Diagnostics {
                tag_filter: None,
                operations: 1,
                pruned_credential_fields: 0,
            },
        );
        assert!(readme.contains("| Prune duplicate credential fields | enabled — not triggered |"));
    }
}
