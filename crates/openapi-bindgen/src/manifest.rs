//! Render a `Cargo.toml` manifest for a generated component crate.

use crate::PackageName;

/// Render the `Cargo.toml` for the generated WebAssembly component crate.
///
/// The crate builds as a `cdylib` (the component shape) and depends on `wit-bindgen`
/// for the exported component bindings and `serde_json`, which the generated
/// `*_to_json` helpers use. The crate name and version are taken from `package`.
pub(crate) fn render(package: &PackageName) -> String {
    let name = &package.name;
    let version = package.version.as_deref().unwrap_or("0.1.0");
    format!(
        r#"# AUTOGENERATED by openapi-bindgen. Do not edit by hand.
[package]
name = "{name}"
version = "{version}"
edition = "2021"

[lib]
crate-type = ["cdylib"]

[dependencies]
serde_json = "1"
wit-bindgen = "0.41"
"#
    )
}

/// Render the `wasm.toml` declaring the WIT interface dependencies a generated component
/// imports: `wasi:http` (to perform requests) and `wasmcloud:secrets` (to fetch
/// credentials). The `component` CLI resolves these into `wit/deps/` before building.
pub(crate) fn render_wasm_deps() -> String {
    r#"# AUTOGENERATED by openapi-bindgen. Do not edit by hand.
[dependencies.components]

[dependencies.interfaces]
"wasi:http@0.2.3" = "0.2.3"
"wasmcloud:secrets@1.0.0" = "1.0.0"
"#
    .to_string()
}
