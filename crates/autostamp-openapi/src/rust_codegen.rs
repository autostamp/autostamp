/// The shared request + auth runtime, embedded verbatim into every generated component as a
/// private `runtime` module. It lives outside `src/` so it is not compiled into the
/// generator itself — only emitted into generated crates, where the `wstd` (HTTP) and
/// `wasmcloud:secrets` bindings it references exist.
const RUNTIME_SRC: &str = include_str!("../templates/runtime.rs");

pub(crate) fn emit_rust(
    ifaces: &[InterfaceModel],
    package: &PackageName,
    base_url: &str,
) -> Vec<crate::RustSource> {
    // The crate root: shared bindings and runtime, plus a `mod` declaration per interface. Each
    // interface's `Guest` impl and helpers live in their own `iface_<name>.rs` module (emitted
    // below), so no single file grows too large for `rustc` to parse. `export!(Component)` comes
    // last, once every interface module — and thus every `Guest` impl — is declared and in scope.
    let mut lib = String::new();
    lib.push_str("// AUTOGENERATED by openapi-bindgen. Do not edit by hand.\n");
    lib.push_str("#![allow(unused, clippy::all, non_snake_case)]\n\n");

    // Component bindings for the generated `client` world (defined in `wit/`). `generate_all`
    // emits bindings for the `wasmcloud:secrets` interfaces the world imports (plus any of
    // their transitive deps). The HTTP host binding is provided separately by the `wstd` crate.
    lib.push_str(
        "wit_bindgen::generate!({\n    world: \"client\",\n    path: \"wit\",\n    generate_all,\n});\n\n",
    );

    // The base URL resolved from the OpenAPI `servers` list; the runtime builds absolute
    // request URLs from it.
    lib.push_str("/// The API base URL, resolved from the OpenAPI `servers` list.\n");
    lib.push_str(&format!("const BASE_URL: &str = {base_url:?};\n\n"));

    // The component entry point; one `Guest` impl per generated interface lives in its module,
    // and `export!(Component)` is emitted at the end once those impls are in scope.
    lib.push_str("/// The component entry point implementing the generated interfaces.\n");
    lib.push_str("struct Component;\n\n");

    // The shared request + auth runtime, fetching credentials from `wasmcloud:secrets` and
    // performing the call with the `wstd` HTTP client (which talks to the host over `wasi:http`).
    lib.push_str("mod runtime {\n");
    lib.push_str(RUNTIME_SRC);
    lib.push_str("}\n\n");

    // One module per interface, each in its own `iface_<name>.rs` file.
    let mut files = Vec::with_capacity(ifaces.len() + 1);
    for iface in ifaces {
        let module = to_rust_ident(&iface.name_kebab);
        let mod_snake = format!("iface_{module}");
        lib.push_str(&format!("mod {mod_snake};\n"));
        files.push(crate::RustSource {
            path: format!("{mod_snake}.rs"),
            contents: emit_interface(iface, package),
        });
    }

    // Export the component once every interface module (and its `Guest` impl) is declared above.
    lib.push_str("\nexport!(Component);\n");

    let mut out = Vec::with_capacity(files.len() + 1);
    out.push(crate::RustSource {
        path: "lib.rs".to_string(),
        contents: lib,
    });
    out.extend(files);
    out
}

/// Emit the standalone `iface_<name>.rs` module for a single interface: its `OpSpec` consts,
/// `*_to_json` / `*_from_json` / `*_to_str` / `*_from_str` helpers, per-op response adapters, and
/// the `impl Guest for crate::Component`. Everything here is interface-scoped and references only
/// crate-level shared items (`crate::Component`, `crate::runtime`, `crate::exports`, `serde_json`),
/// so each module compiles independently of the others.
fn emit_interface(iface: &InterfaceModel, package: &PackageName) -> String {
    let mut out = String::new();
    out.push_str("// AUTOGENERATED by openapi-bindgen. Do not edit by hand.\n\n");

    out.push_str(
        "use crate::runtime::{dispatch, AuthApply, AuthKind, FieldLocation, FieldSpec, OpSpec};\n",
    );

    let rust_path = package.rust_path();
    {
        // Alias the exported-interface module to a collision-proof local name. An interface
        // whose name maps to `exports`, `wasi`, or `wasmcloud` would otherwise shadow the
        // top-level modules wit-bindgen generates — the synthetic `exports` macro module and
        // the `wasi`/`wasmcloud` import namespaces — yielding E0255 "defined multiple times"
        // (mandrillapp and zuora both expose an `Exports` tag). The `iface_` prefix can't
        // collide with those, with `runtime`, or with the generated helper/const names.
        let module = to_rust_ident(&iface.name_kebab);
        let mod_snake = format!("iface_{module}");
        out.push_str(&format!(
            "use crate::exports::{rust_path}::{module} as {mod_snake};\n"
        ));
        out.push_str("use serde_json::{Map, Value};\n\n");

        // OpSpec consts
        for op in &iface.operations {
            let const_name = op_const_name(iface, op);
            out.push_str(&format!("const {const_name}: OpSpec = OpSpec {{\n"));
            out.push_str(&format!("    method: {:?},\n", op.method));
            out.push_str(&format!(
                "    path_template: {:?},\n",
                snake_path_template(&op.path_template)
            ));
            out.push_str("    fields: &[\n");
            for f in &op.fields {
                let loc = match f.location {
                    Location::Path => "FieldLocation::Path",
                    Location::Query => "FieldLocation::Query",
                    Location::Header => "FieldLocation::Header",
                    Location::Body => "FieldLocation::Body",
                };
                out.push_str(&format!(
                    "        FieldSpec {{ snake: {:?}, wire: {:?}, location: {loc} }},\n",
                    f.name_snake, f.wire_name
                ));
            }
            out.push_str("    ],\n");
            emit_auth_table(&mut out, &op.auth);
            out.push_str("};\n\n");
        }

        // Enum -> &'static str helpers (namespaced by interface to avoid collisions)
        for e in &iface.enums {
            let fn_name = helper_name(&mod_snake, &e.name_kebab, "to_str");
            let pascal = to_rust_type_name(&e.name_kebab);
            out.push_str(&format!(
                "fn {fn_name}(e: &{mod_snake}::{pascal}) -> &'static str {{\n"
            ));
            out.push_str("    match e {\n");
            for (kebab, raw) in &e.cases {
                let case_pascal = to_rust_case_name(kebab);
                // Emit the wire value with `{:?}` so any character the API declares in the enum
                // value — embedded quotes (Telnyx ships `"Ashburn, VA"`, quotes and all),
                // backslashes, newlines — is escaped into a valid Rust string literal instead of
                // producing `""Ashburn, VA""` (a reserved-prefix lex error).
                out.push_str(&format!(
                    "        {mod_snake}::{pascal}::{case_pascal} => {raw:?},\n"
                ));
            }
            out.push_str("    }\n");
            out.push_str("}\n\n");
        }

        // Record -> Value helpers (for both supporting records and per-op params records)
        for r in &iface.records {
            emit_record_to_json(&mut out, &mod_snake, &r.name_kebab, &r.fields, iface, true);
        }
        for op in &iface.operations {
            if !op.fields.is_empty() {
                emit_record_to_json(
                    &mut out,
                    &mod_snake,
                    &op.params_record,
                    &op.fields,
                    iface,
                    false,
                );
            }
        }

        // Value -> record / &str -> enum decoders, emitted only for the types reachable from a
        // response `ok` body (a record used solely as a request body needs no decoder).
        let response_types = response_reachable_types(iface);
        for r in &iface.records {
            if response_types.contains(&r.name_kebab) {
                emit_record_from_json(&mut out, &mod_snake, &r.name_kebab, &r.fields, iface);
            }
        }
        for e in &iface.enums {
            if response_types.contains(&e.name_kebab) {
                emit_enum_from_str(&mut out, &mod_snake, e);
            }
        }

        // Per-operation response adapters: decode the ok body into its typed value, and map a
        // `DispatchError` onto the operation's typed error (a variant case or a plain string).
        for op in &iface.operations {
            emit_op_ok(&mut out, &mod_snake, op, iface);
            emit_op_err(&mut out, &mod_snake, op, iface);
        }

        // Guest impl
        out.push_str(&format!(
            "impl {mod_snake}::Guest for crate::Component {{\n"
        ));
        for op in &iface.operations {
            let const_name = op_const_name(iface, op);
            let ok_rust = rust_type_of(&op.ok_ty, &mod_snake);
            let err_rust = rust_type_of(&op.err_ty, &mod_snake);
            let ok_fn = helper_name(&mod_snake, &op.op_kebab, "ok");
            let err_fn = helper_name(&mod_snake, &op.op_kebab, "err");
            if op.fields.is_empty() {
                out.push_str(&format!(
                    "    fn {}() -> Result<{ok_rust}, {err_rust}> {{\n",
                    op.op_snake
                ));
                out.push_str(&format!(
                    "        match dispatch(&{const_name}, Value::Object(Map::new())).and_then({ok_fn}) {{\n"
                ));
            } else {
                let params_pascal = to_rust_type_name(&op.params_record);
                let to_json = helper_name(&mod_snake, &op.params_record, "to_json");
                out.push_str(&format!(
                    "    fn {}(params: {mod_snake}::{params_pascal}) -> Result<{ok_rust}, {err_rust}> {{\n",
                    op.op_snake
                ));
                out.push_str(&format!("        let json = {to_json}(&params);\n"));
                out.push_str(&format!(
                    "        match dispatch(&{const_name}, json).and_then({ok_fn}) {{\n"
                ));
            }
            out.push_str("            Ok(v) => Ok(v),\n");
            out.push_str(&format!("            Err(e) => Err({err_fn}(e)),\n"));
            out.push_str("        }\n");
            out.push_str("    }\n");
        }
        out.push_str("}\n");
    }

    out
}

/// Emit the `auth: &[AuthApply { .. }]` table for an operation's resolved security schemes,
/// translating the generator-side [`AuthKind`] into the runtime's literal form.
fn emit_auth_table(out: &mut String, auth: &[AuthApply]) {
    out.push_str("    auth: &[\n");
    for a in auth {
        let kind = match &a.kind {
            AuthKind::Bearer => "AuthKind::Bearer".to_string(),
            AuthKind::Basic => "AuthKind::Basic".to_string(),
            AuthKind::ApiKeyHeader { name } => format!("AuthKind::ApiKeyHeader({name:?})"),
            AuthKind::ApiKeyQuery { name } => format!("AuthKind::ApiKeyQuery({name:?})"),
            AuthKind::ApiKeyCookie { name } => format!("AuthKind::ApiKeyCookie({name:?})"),
        };
        out.push_str(&format!(
            "        AuthApply {{ secret_key: {:?}, kind: {kind} }},\n",
            a.secret_key
        ));
    }
    out.push_str("    ],\n");
}

/// Snake-case the `{token}` placeholders in a path template so they match the snake-cased
/// field keys the runtime substitutes. `/users/{userId}` becomes `/users/{user_id}`.
fn snake_path_template(path: &str) -> String {
    let mut out = String::with_capacity(path.len());
    let mut rest = path;
    while let Some(open) = rest.find('{') {
        out.push_str(&rest[..open]);
        let after = &rest[open + 1..];
        match after.find('}') {
            Some(close) => {
                out.push('{');
                out.push_str(&after[..close].to_snake_case());
                out.push('}');
                rest = &after[close + 1..];
            }
            None => {
                // Unbalanced brace: emit the remainder verbatim.
                out.push_str(&rest[open..]);
                return out;
            }
        }
    }
    out.push_str(rest);
    out
}

fn op_const_name(iface: &InterfaceModel, op: &crate::operation_model::OperationModel) -> String {
    format!(
        "OP_{}_{}",
        iface.name_kebab.replace('-', "_").to_uppercase(),
        op.op_snake.to_uppercase()
    )
}

/// Build an interface-scoped helper name. `kebab` is the kebab-case type name;
/// `suffix` is e.g. "to_json" or "to_str".
fn helper_name(mod_snake: &str, kebab: &str, suffix: &str) -> String {
    let body = kebab.replace('-', "_");
    format!("{mod_snake}__{body}__{suffix}")
}

/// Emit a `record -> serde_json::Value` helper for a params or supporting record.
///
/// `key_by_wire` selects the JSON key for each field. Supporting records (`iface.records`) model
/// request-body shapes that go on the wire verbatim, so they key by `wire_name`. The synthetic
/// per-operation params record is internal plumbing — the runtime reads it back by `name_snake`
/// and re-keys each field to its wire name during dispatch — so it keys by `name_snake`.
fn emit_record_to_json(
    out: &mut String,
    mod_snake: &str,
    record_kebab: &str,
    fields: &[Field],
    iface: &InterfaceModel,
    key_by_wire: bool,
) {
    let fn_name = helper_name(mod_snake, record_kebab, "to_json");
    let pascal = to_rust_type_name(record_kebab);
    out.push_str(&format!(
        "fn {fn_name}(p: &{mod_snake}::{pascal}) -> Value {{\n"
    ));
    out.push_str("    let mut m = Map::new();\n");
    for f in fields {
        let field_snake = to_rust_ident(&f.name_kebab);
        let expr = field_to_json_expr(&format!("&p.{field_snake}"), &f.ty, iface, mod_snake);
        let key = if key_by_wire {
            &f.wire_name
        } else {
            &f.name_snake
        };
        out.push_str(&format!("    m.insert(\"{key}\".into(), {expr});\n"));
    }
    out.push_str("    Value::Object(m)\n");
    out.push_str("}\n\n");
}

/// Render an expression that converts `expr` (always a `&T` reference) into a `Value`.
fn field_to_json_expr(expr: &str, ty: &WitType, iface: &InterfaceModel, mod_snake: &str) -> String {
    match ty {
        WitType::String => format!("Value::String(({expr}).clone())"),
        WitType::Bool => format!("Value::Bool(*({expr}))"),
        WitType::S32 | WitType::S64 => {
            format!("Value::Number(serde_json::Number::from(*({expr})))")
        }
        WitType::F64 => format!(
            "serde_json::Number::from_f64(*({expr})).map(Value::Number).unwrap_or(Value::Null)"
        ),
        WitType::Option(inner) => {
            let inner_expr = field_to_json_expr("v", inner, iface, mod_snake);
            format!("match ({expr}) {{ Some(v) => {inner_expr}, None => Value::Null }}")
        }
        WitType::List(inner) => {
            let inner_expr = field_to_json_expr("v", inner, iface, mod_snake);
            format!("Value::Array(({expr}).iter().map(|v| {inner_expr}).collect())")
        }
        WitType::Map { value, .. } => {
            // `Vec<Entry>` -> a JSON object `{key: value}`. serde's default would encode the list
            // as an array of `{key, value}` objects; because this serializer is hand-rolled we
            // emit the real map object the wire expects.
            let val_expr = field_to_json_expr("&e.value", value, iface, mod_snake);
            format!("Value::Object(({expr}).iter().map(|e| (e.key.clone(), {val_expr})).collect())")
        }
        WitType::Named(name) => {
            if iface.is_enum(name) {
                let fn_name = helper_name(mod_snake, name, "to_str");
                format!("Value::String({fn_name}({expr}).into())")
            } else if iface.is_record(name) {
                let fn_name = helper_name(mod_snake, name, "to_json");
                format!("{fn_name}({expr})")
            } else {
                "Value::Null".into()
            }
        }
    }
}

/// The Rust type wit-bindgen generates for `ty` in an exported function's *return* position:
/// owned scalars/strings, `Option`/`Vec` wrappers, and `{mod}::{Pascal}` for a named
/// record/enum/variant (all defined in the exported-interface module aliased to `mod_snake`).
fn rust_type_of(ty: &WitType, mod_snake: &str) -> String {
    match ty {
        WitType::String => "String".into(),
        WitType::Bool => "bool".into(),
        WitType::S32 => "i32".into(),
        WitType::S64 => "i64".into(),
        WitType::F64 => "f64".into(),
        WitType::Option(inner) => format!("Option<{}>", rust_type_of(inner, mod_snake)),
        WitType::List(inner) => format!("Vec<{}>", rust_type_of(inner, mod_snake)),
        WitType::Map { entry, .. } => format!("Vec<{mod_snake}::{}>", to_rust_type_name(entry)),
        WitType::Named(name) => format!("{mod_snake}::{}", to_rust_type_name(name)),
    }
}

/// The set of record/enum names reachable from any operation's response `ok` type, following
/// record→field edges to a fixpoint. Only these need a decoder emitted; a record used solely as
/// a request body is serialized, never deserialized.
fn response_reachable_types(iface: &InterfaceModel) -> BTreeSet<String> {
    let mut reachable: BTreeSet<String> = BTreeSet::new();
    let mut work: Vec<String> = Vec::new();
    for op in &iface.operations {
        for n in named_of(&op.ok_ty) {
            if reachable.insert(n.clone()) {
                work.push(n);
            }
        }
    }
    while let Some(name) = work.pop() {
        if let Some(r) = iface.records.iter().find(|r| r.name_kebab == name) {
            for f in &r.fields {
                for n in named_of(&f.ty) {
                    if reachable.insert(n.clone()) {
                        work.push(n);
                    }
                }
            }
        }
    }
    reachable
}

/// The named types directly referenced by `ty` (unwrapping `option`/`list`).
fn named_of(ty: &WitType) -> Vec<String> {
    match ty {
        WitType::Named(n) => vec![n.clone()],
        WitType::Option(inner) | WitType::List(inner) => named_of(inner),
        WitType::Map { entry, value } => {
            let mut names = vec![entry.clone()];
            names.extend(named_of(value));
            names
        }
        _ => vec![],
    }
}

/// Emit a `&Value -> Option<Record>` decoder mirroring [`emit_record_to_json`]. Reads each field
/// by its verbatim wire name. A missing/mismatched scalar or list defaults; a missing/mismatched
/// required nested record or enum (which has no `Default`) fails the whole decode by returning
/// `None`, so the operation surfaces the raw body as an error rather than fabricating a value.
fn emit_record_from_json(
    out: &mut String,
    mod_snake: &str,
    record_kebab: &str,
    fields: &[Field],
    iface: &InterfaceModel,
) {
    let fn_name = helper_name(mod_snake, record_kebab, "from_json");
    let pascal = to_rust_type_name(record_kebab);
    out.push_str(&format!(
        "fn {fn_name}(v: &Value) -> Option<{mod_snake}::{pascal}> {{\n"
    ));
    out.push_str("    let m = v.as_object()?;\n");
    out.push_str(&format!("    Some({mod_snake}::{pascal} {{\n"));
    for f in fields {
        let field_rust = to_rust_ident(&f.name_kebab);
        let init = field_from_json_expr(&f.wire_name, &f.ty, iface, mod_snake);
        out.push_str(&format!("        {field_rust}: {init},\n"));
    }
    out.push_str("    })\n");
    out.push_str("}\n\n");
}

/// Render the initializer expression for a record field decoded from the object map `m`.
fn field_from_json_expr(
    wire: &str,
    ty: &WitType,
    iface: &InterfaceModel,
    mod_snake: &str,
) -> String {
    match ty {
        WitType::Option(inner) => {
            let val = from_value_expr("v", inner, iface, mod_snake);
            format!("m.get({wire:?}).filter(|v| !v.is_null()).and_then(|v| {val})")
        }
        WitType::Named(name) if iface.is_record(name) || iface.is_enum(name) => {
            let val = from_value_expr("v", ty, iface, mod_snake);
            format!(
                "match m.get({wire:?}).and_then(|v| {val}) {{ Some(x) => x, None => return None }}"
            )
        }
        _ => {
            let val = from_value_expr("v", ty, iface, mod_snake);
            format!("m.get({wire:?}).and_then(|v| {val}).unwrap_or_default()")
        }
    }
}

/// Render an expression that decodes `v` (a `&Value`) into `Option<RustType>` for `ty`.
fn from_value_expr(v: &str, ty: &WitType, iface: &InterfaceModel, mod_snake: &str) -> String {
    match ty {
        WitType::String => format!("({v}).as_str().map(|s| s.to_string())"),
        WitType::Bool => format!("({v}).as_bool()"),
        WitType::S32 => format!("({v}).as_i64().map(|n| n as i32)"),
        WitType::S64 => format!("({v}).as_i64()"),
        WitType::F64 => format!("({v}).as_f64()"),
        // An `option` value is decoded as its inner type; presence is handled at the field level.
        WitType::Option(inner) => from_value_expr(v, inner, iface, mod_snake),
        WitType::List(inner) => {
            let inner_expr = from_value_expr("x", inner, iface, mod_snake);
            format!("({v}).as_array().map(|a| a.iter().filter_map(|x| {inner_expr}).collect())")
        }
        WitType::Map { entry, value } => {
            // A JSON object `{key: value}` -> `Vec<Entry>`, dropping entries whose value fails to
            // decode (mirrors the list arm's `filter_map`).
            let inner_expr = from_value_expr("x", value, iface, mod_snake);
            let entry_pascal = to_rust_type_name(entry);
            format!(
                "({v}).as_object().map(|o| o.iter().filter_map(|(k, x)| ({inner_expr}).map(|val| {mod_snake}::{entry_pascal} {{ key: k.clone(), value: val }})).collect())"
            )
        }
        WitType::Named(name) => {
            if iface.is_enum(name) {
                let fn_name = helper_name(mod_snake, name, "from_str");
                format!("({v}).as_str().and_then({fn_name})")
            } else if iface.is_record(name) {
                let fn_name = helper_name(mod_snake, name, "from_json");
                format!("{fn_name}({v})")
            } else {
                // A variant is never a value-level type in our model (errors only).
                "None".into()
            }
        }
    }
}

/// Emit a `&str -> Option<Enum>` decoder, the inverse of the enum's `to_str` helper.
fn emit_enum_from_str(out: &mut String, mod_snake: &str, e: &EnumModel) {
    let fn_name = helper_name(mod_snake, &e.name_kebab, "from_str");
    let pascal = to_rust_type_name(&e.name_kebab);
    out.push_str(&format!(
        "fn {fn_name}(s: &str) -> Option<{mod_snake}::{pascal}> {{\n"
    ));
    out.push_str("    match s {\n");
    for (kebab, raw) in &e.cases {
        let case_pascal = to_rust_case_name(kebab);
        out.push_str(&format!(
            "        {raw:?} => Some({mod_snake}::{pascal}::{case_pascal}),\n"
        ));
    }
    out.push_str("        _ => None,\n");
    out.push_str("    }\n");
    out.push_str("}\n\n");
}

/// Emit the per-op `ok` adapter: `String -> Result<OkType, DispatchError>`. A `string` ok type
/// returns the raw body verbatim; any other type parses the body as JSON and decodes it,
/// surfacing a parse/shape mismatch as a `Transport` error (mapped to the op's catch-all).
fn emit_op_ok(out: &mut String, mod_snake: &str, op: &OperationModel, iface: &InterfaceModel) {
    let ok_rust = rust_type_of(&op.ok_ty, mod_snake);
    let fn_name = helper_name(mod_snake, &op.op_kebab, "ok");
    out.push_str(&format!(
        "fn {fn_name}(body: String) -> Result<{ok_rust}, crate::runtime::DispatchError> {{\n"
    ));
    match &op.ok_ty {
        WitType::String => out.push_str("    Ok(body)\n"),
        ty => {
            out.push_str("    let v: Value = match serde_json::from_str(&body) {\n");
            out.push_str("        Ok(v) => v,\n");
            out.push_str("        Err(e) => return Err(crate::runtime::DispatchError::Transport(format!(\"failed to decode response body as JSON: {e}\"))),\n");
            out.push_str("    };\n");
            let expr = from_value_expr("&v", ty, iface, mod_snake);
            out.push_str(&format!("    match {expr} {{\n"));
            out.push_str("        Some(x) => Ok(x),\n");
            out.push_str("        None => Err(crate::runtime::DispatchError::Transport(\"response body did not match the expected schema\".to_string())),\n");
            out.push_str("    }\n");
        }
    }
    out.push_str("}\n\n");
}

/// Emit the per-op `err` adapter: `DispatchError -> ErrType`. For a `string` error type this
/// flattens to a message (preserving the original `HTTP {status}: {body}` form); for an
/// enumerated variant it routes each HTTP status to its case (specific codes first, then status
/// ranges) and sends transport failures and undeclared statuses to the catch-all `other` case.
fn emit_op_err(out: &mut String, mod_snake: &str, op: &OperationModel, iface: &InterfaceModel) {
    let err_rust = rust_type_of(&op.err_ty, mod_snake);
    let fn_name = helper_name(mod_snake, &op.op_kebab, "err");
    out.push_str(&format!(
        "fn {fn_name}(e: crate::runtime::DispatchError) -> {err_rust} {{\n"
    ));
    match &op.err_ty {
        WitType::Named(name) if iface_variant(iface, name).is_some() => {
            let variant = iface_variant(iface, name).expect("variant present");
            let pascal = to_rust_type_name(name);
            let other = variant
                .cases
                .iter()
                .find(|c| c.status == CaseStatus::Other)
                .map(|c| to_rust_case_name(&c.name_kebab))
                .unwrap_or_else(|| "Other".to_string());
            out.push_str("    match e {\n");
            out.push_str(
                "        crate::runtime::DispatchError::Http { status, body } => match status {\n",
            );
            for case in &variant.cases {
                if let CaseStatus::Code(code) = case.status {
                    let cp = to_rust_case_name(&case.name_kebab);
                    out.push_str(&format!(
                        "            {code}u16 => {mod_snake}::{pascal}::{cp}(body),\n"
                    ));
                }
            }
            for case in &variant.cases {
                if let CaseStatus::Range(r) = case.status {
                    let cp = to_rust_case_name(&case.name_kebab);
                    let lo = u16::from(r) * 100;
                    let hi = lo + 100;
                    out.push_str(&format!(
                        "            s if ({lo}u16..{hi}u16).contains(&s) => {mod_snake}::{pascal}::{cp}(body),\n"
                    ));
                }
            }
            out.push_str(&format!(
                "            _ => {mod_snake}::{pascal}::{other}(body),\n"
            ));
            out.push_str("        },\n");
            out.push_str(&format!(
                "        crate::runtime::DispatchError::Transport(m) => {mod_snake}::{pascal}::{other}(m),\n"
            ));
            out.push_str("    }\n");
        }
        _ => {
            out.push_str("    match e {\n");
            out.push_str("        crate::runtime::DispatchError::Http { status, body } => format!(\"HTTP {status}: {body}\"),\n");
            out.push_str("        crate::runtime::DispatchError::Transport(m) => m,\n");
            out.push_str("    }\n");
        }
    }
    out.push_str("}\n\n");
}

/// Find the variant model named `name` in `iface`, if any.
fn iface_variant<'a>(iface: &'a InterfaceModel, name: &str) -> Option<&'a VariantModel> {
    iface.variants.iter().find(|v| v.name_kebab == name)
}
