//! Self-contained client component generation.

use crate::{Catalog, Error, PackageName, generate_wit, runtime, rust_codegen};

/// Configuration embedded into a generated client.
#[derive(Debug, Clone, Default)]
pub struct GenerateOptions {
    /// Streamable HTTP endpoint. No request is made during generation.
    pub endpoint: String,
    /// A `wasmcloud:secrets` key, never the bearer token itself.
    pub bearer_secret: Option<String>,
    /// Per-request timeout and response/event byte bounds.
    pub limits: runtime::Limits,
}

/// One generated source file, relative to the component's `src/` directory.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RustSource {
    /// Relative file path, including subdirectories where needed.
    pub path: String,
    /// UTF-8 source contents.
    pub contents: String,
}

/// One vendored WIT dependency, relative to the component's `wit/` directory.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WitDependency {
    /// Relative file path below `wit/`, including `deps/`.
    pub path: String,
    /// Complete dependency source.
    pub contents: String,
}

/// Everything needed to build a standalone typed MCP client component.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Generated {
    /// The client world, written to `wit/world.wit`.
    pub wit: String,
    /// Rust sources, beginning with `lib.rs`.
    pub rust: Vec<RustSource>,
    /// Standalone Cargo manifest, independent of the generator workspace.
    pub cargo_toml: String,
    /// Component manifest.
    pub wasm_toml: String,
    /// Build instructions and the generated client's contract.
    pub readme: String,
    /// WIT dependencies to write verbatim; no network resolution is required.
    pub wit_dependencies: Vec<WitDependency>,
}

const SECRETS_WIT: &str = include_str!("../../../vendor/wit/wasmcloud-secrets-1.0.0.wit");

/// Generate a standalone client without discovering or invoking any MCP tools.
///
/// The endpoint and optional secret *key* are embedded as data, not Rust source.
/// Anonymous clients have no secrets imports and need no secrets provider.
/// Unsupported schemas are rejected when constructing [`Catalog`].
pub fn generate(
    catalog: &Catalog,
    package: &PackageName,
    options: &GenerateOptions,
) -> Result<Generated, Error> {
    validate_options(options)?;
    let mut wit = generate_wit(catalog, package)?;
    let mut wit_dependencies = Vec::new();
    if options.bearer_secret.is_some() {
        wit = wit.replace(
            "world client {\n",
            "world client {\n    import wasmcloud:secrets/store@1.0.0;\n    import wasmcloud:secrets/reveal@1.0.0;\n",
        );
        wit_dependencies.push(WitDependency {
            path: "deps/wasmcloud-secrets/secrets.wit".into(),
            contents: SECRETS_WIT.into(),
        });
    }
    let mut resolve = wit_parser::Resolve::default();
    for dependency in &wit_dependencies {
        resolve
            .push_str(&dependency.path, &dependency.contents)
            .map_err(|err| Error::new(None, "", format!("invalid WIT dependency: {err:#}")))?;
    }
    resolve
        .push_str("world.wit", &wit)
        .map_err(|err| Error::new(None, "", format!("invalid client WIT: {err:#}")))?;

    let name = package.name();
    let namespace = package.namespace();
    let version = package.version().unwrap_or("0.1.0");
    let cargo_toml = format!(
        r#"# Generated by autostamp-mcp.
[package]
name = "{name}"
version = "{version}"
edition = "2024"

[lib]
crate-type = ["cdylib", "rlib"]
doctest = false

[dependencies]
http = "1"
serde = "1"
serde_json = {{ version = "1", features = ["arbitrary_precision", "float_roundtrip", "raw_value"] }}
wit-bindgen = "0.41"

[target.'cfg(target_arch = "wasm32")'.dependencies]
wstd = {{ version = "0.6", default-features = false }}

[profile.release]
opt-level = "s"

[workspace]
"#
    );
    let wasm_toml = format!(
        r#"# Generated by autostamp-mcp. WIT dependencies are vendored.
[package]
name = "{namespace}:{name}"
version = "{version}"
kind = "component"
file = "target/wasm32-wasip2/release/{}.wasm"
"#,
        name.replace('-', "_"),
    );
    let authentication = if options.bearer_secret.is_some() {
        "The configured secret key is resolved through `wasmcloud:secrets/store` and \
         `wasmcloud:secrets/reveal` at call time. Supply those imports when running the component. \
         No credential value is embedded in the sources."
    } else {
        "This client is anonymous. It imports no secrets interfaces and needs no secrets provider."
    };
    let readme = format!(
        "# {namespace}:{name}\n\n\
         Generated by `autostamp-mcp` from an offline, complete tools/list catalog.\n\n\
         ## Build\n\n\
         ```sh\ncargo build --release --target wasm32-wasip2\n```\n\n\
         All WIT dependencies and runtime sources are included. No autostamp crates are needed \
         to build this client. Run it with a WASI 0.2 host supporting outgoing HTTP.\n\n\
         ## Authentication\n\n{authentication}\n\n\
         ## Contract\n\n\
         Each synchronous tool export performs MCP Streamable HTTP calls. Tools without \
         outputSchema return the complete result-envelope JSON. Typed results preserve both \
         structured content and the original envelope. Tool failures preserve the entire \
         envelope and are checked before typed decoding.\n\n\
         Codecs enforce wire types, requiredness, nullability, enum membership, closed objects, \
         unique map/extra keys, integer ranges and finite floating-point representations. \
         Optional nullable properties preserve missing, null and value separately. JSON Schema \
         annotations and validation constraints such as pattern/minimum are documented, not \
         implemented as a full JSON Schema validator. No untyped schema fallback is used.\n\n\
         Configured limits: {} ms per request, {} response bytes, {} event bytes.\n",
        options.limits.request_timeout_ms,
        options.limits.max_response_bytes,
        options.limits.max_event_bytes,
    );
    Ok(Generated {
        wit,
        rust: rust_codegen::emit(catalog, package, options),
        cargo_toml,
        wasm_toml,
        readme,
        wit_dependencies,
    })
}

fn validate_options(options: &GenerateOptions) -> Result<(), Error> {
    runtime::validate_endpoint(&options.endpoint)
        .map_err(|error| Error::new(None, "", error.to_string()))?;
    options
        .limits
        .validate()
        .map_err(|error| Error::new(None, "", error.to_string()))?;
    if options
        .bearer_secret
        .as_ref()
        .is_some_and(|key| key.is_empty() || key.chars().any(char::is_control))
    {
        return Err(Error::new(
            None,
            "",
            "bearer secret key must be nonempty and contain no control characters",
        ));
    }
    if u32::try_from(options.limits.max_response_bytes).is_err()
        || u32::try_from(options.limits.max_event_bytes).is_err()
    {
        return Err(Error::new(
            None,
            "",
            "byte limits must fit the wasm32 address space",
        ));
    }
    Ok(())
}
